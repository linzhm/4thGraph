# Check the ForkID SINGLE preimage format, input amount and same-index TxOut.
block CHECK_PAIRED_OUTPUT
  OP_DEPTH OP_DUP OP_1 OP_3 OP_WITHIN OP_VERIFY
  OP_2 OP_NUMEQUAL OP_DUP OP_TOALTSTACK
  OP_IF
    OP_SIZE 161 OP_NUMEQUALVERIFY
    OP_DUP 104 OP_SPLIT OP_NIP 5 OP_SPLIT OP_SWAP 0x04ad68abac OP_EQUALVERIFY
  OP_ELSE
    OP_SIZE 158 OP_NUMEQUALVERIFY
    OP_DUP 104 OP_SPLIT OP_NIP 2 OP_SPLIT OP_SWAP 0x01ac OP_EQUALVERIFY
  OP_ENDIF
  OP_8 OP_SPLIT OP_SWAP @VALUE OP_EQUALVERIFY
  OP_4 OP_SPLIT OP_NIP 32 OP_SPLIT OP_DROP
  # A missing same-index output has a zero hash under ForkID SINGLE.
  OP_DUP OP_0 32 OP_NUM2BIN OP_EQUAL OP_NOT OP_VERIFY
  @TARGET_HASH OP_EQUALVERIFY
end

# Authenticate that preimage and, when present, the separately selected digest.
block BIND_ACTIVATION_TRANSACTION
  OP_DUP OP_SIZE OP_4 OP_SUB OP_SPLIT OP_NIP OP_1 OP_SPLIT 0x000000 OP_EQUALVERIFY
  OP_DUP @IS_FORKID_SINGLE OP_VERIFY
  OP_FROMALTSTACK OP_DUP OP_TOALTSTACK OP_IF
    2 OP_PICK OP_1 OP_SPLIT OP_DROP 0x80 OP_AND OP_OVER 0x80 OP_AND OP_EQUALVERIFY
  OP_ENDIF
  OP_TOALTSTACK
  OP_HASH256 @UINT256BE @K1_BIND_DIGEST
  OP_FROMALTSTACK OP_DUP OP_TOALTSTACK OP_IF
    OP_ROT OP_SIZE 33 OP_NUMEQUALVERIFY OP_1 OP_SPLIT OP_SWAP
    OP_DUP 0x000000 OP_CAT @CHECK_TYPE
    OP_DUP @IS_FORKID_SINGLE OP_NOT OP_VERIFY OP_TOALTSTACK
    @UINT256BE @K1_BIND_DIGEST OP_2SWAP
  OP_ENDIF
  OP_FROMALTSTACK OP_IF OP_CODESEPARATOR OP_CHECKSIGVERIFY OP_ENDIF
  OP_CODESEPARATOR OP_CHECKSIG
end
