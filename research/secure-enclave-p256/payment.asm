block LOCK
  # parent P Q signature
  OP_OVER OP_HASH160 @OWNER OP_EQUALVERIFY
  OP_DEPTH 4 OP_NUMEQUALVERIFY
  2 OP_PICK OP_SIZE 158 OP_NUMEQUALVERIFY OP_DROP
  OP_OVER OP_SIZE 65 OP_NUMEQUALVERIFY OP_DROP
  OP_SIZE 64 OP_NUMEQUALVERIFY
  3 OP_PICK OP_HASH256 3 OP_PICK 68 OP_SPLIT OP_NIP 32 OP_SPLIT OP_DROP OP_EQUALVERIFY
  2 OP_PICK 104 OP_SPLIT OP_NIP 2 OP_SPLIT OP_DROP 0x01ac OP_EQUALVERIFY

  # Type includes all four bytes of its LE32 representation.
  2 OP_PICK 154 OP_SPLIT OP_NIP
  OP_DUP 0x41000000 OP_EQUAL @ALLOW_ALL OP_BOOLAND
  OP_OVER 0xc1000000 OP_EQUAL @ALLOW_ALL_ACP OP_BOOLAND OP_BOOLOR
  OP_OVER 0x42000000 OP_EQUAL @ALLOW_NONE OP_BOOLAND OP_BOOLOR
  OP_OVER 0xc2000000 OP_EQUAL @ALLOW_NONE_ACP OP_BOOLAND OP_BOOLOR
  OP_OVER 0x43000000 OP_EQUAL @ALLOW_SINGLE OP_BOOLAND OP_BOOLOR
  OP_OVER 0xc3000000 OP_EQUAL @ALLOW_SINGLE_ACP OP_BOOLAND OP_BOOLOR OP_VERIFY
  OP_DUP 0x43000000 OP_EQUAL OP_SWAP 0xc3000000 OP_EQUAL OP_BOOLOR OP_IF
    2 OP_PICK 118 OP_SPLIT OP_NIP 32 OP_SPLIT OP_DROP @ZERO32 OP_EQUAL OP_NOT OP_VERIFY
  OP_ENDIF

  # Preserve P until the final native CHECKSIG. Separate R1 digest and key material.
  2 OP_PICK OP_DUP OP_TOALTSTACK @TAG OP_SWAP OP_CAT OP_SHA256 @UINT256BE OP_TOALTSTACK
  OP_SWAP 1 OP_SPLIT OP_SWAP OP_4 OP_EQUALVERIFY
  32 OP_SPLIT @UINT256BE OP_TOALTSTACK @UINT256BE OP_TOALTSTACK
  32 OP_SPLIT @UINT256BE OP_TOALTSTACK @UINT256BE OP_TOALTSTACK
  OP_2DROP @FIELD
  OP_FROMALTSTACK OP_FROMALTSTACK OP_FROMALTSTACK OP_FROMALTSTACK OP_FROMALTSTACK
  # p r s x y z. Validate both scalars and the explicit finite public point.
  4 OP_PICK OP_1 @N OP_WITHIN OP_VERIFY 3 OP_PICK OP_1 @N OP_WITHIN OP_VERIFY
  2 OP_PICK OP_0 @FIELD OP_WITHIN OP_VERIFY 1 OP_PICK OP_0 @FIELD OP_WITHIN OP_VERIFY
  OP_OVER OP_DUP @M 3 OP_PICK OP_DUP OP_DUP @M 3 OP_SUB @M @B OP_ADD @POS OP_NUMEQUALVERIFY

  @N 4 OP_PICK OP_DUP @INVERT_SCALAR
  OP_TOALTSTACK OP_2DROP OP_FROMALTSTACK
  # p r s x y z invS. Store u=z/s then v=r/s above saved P.
  OP_DUP 2 OP_PICK OP_MUL @N OP_MOD OP_TOALTSTACK
  5 OP_PICK OP_MUL @N OP_MOD OP_TOALTSTACK
  OP_DROP OP_ROT OP_DROP OP_TOALTSTACK OP_TOALTSTACK
  @B3 OP_SWAP
  @WINDOW
  # Reject infinity; X/Z is r, or r+n if below p.
  OP_DUP OP_VERIFY
  OP_DUP @COPY_R_LOW @M 3 OP_PICK OP_NUMEQUAL OP_TOALTSTACK
  @COPY_R_HIGH @N OP_ADD OP_DUP @FIELD OP_LESSTHAN OP_TOALTSTACK
  1 OP_PICK @M 3 OP_PICK OP_NUMEQUAL OP_FROMALTSTACK OP_BOOLAND
  OP_FROMALTSTACK OP_BOOLOR OP_VERIFY
  @CLEAR_POINTS
  OP_FROMALTSTACK

  # P -> native public-parameter signature. WP1605 section 1.1, k=a=1.
  OP_DUP 154 OP_SPLIT OP_NIP 1 OP_SPLIT OP_DROP OP_TOALTSTACK
  OP_HASH256 @UINT256BE @K1_GX OP_ADD @K1_N OP_MOD OP_DUP OP_VERIFY
  OP_DUP @K1_N OP_SWAP OP_SUB OP_MIN
  OP_SIZE OP_TOALTSTACK 32 OP_NUM2BIN @REVERSE32
  32 OP_FROMALTSTACK OP_SUB OP_SPLIT OP_NIP
  OP_SIZE OP_TUCK OP_TOALTSTACK OP_CAT
  @DER_R OP_SWAP OP_CAT OP_FROMALTSTACK 36 OP_ADD
  0x30 OP_SWAP OP_CAT OP_SWAP OP_CAT OP_FROMALTSTACK OP_CAT
  @K1_PUB OP_CODESEPARATOR OP_CHECKSIG
